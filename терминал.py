from пицца import ПиццаПепперони, ПиццаБарбекю, ПиццаДарыМоря
from заказ import Заказ


class Терминал:
    
    КОМПАНИЯ = "Пиццерия #1"
    КОМАНДА_ОТМЕНА_ЗАКАЗА = -1
    КОМАНДА_ПОДТВЕРЖДЕНИЕ_ЗАКАЗА = 0

    def __init__(self):
        self.меню = [ПиццаПепперони(), ПиццаБарбекю(), ПиццаДарыМоря()]
        self.заказ = None
        self.отображать_меню = True

    def __str__(self):
        return f"{self.КОМПАНИЯ}, версия 1.0"

    def показать_меню(self):
        if not self.отображать_меню:
            return
        
        print(self.КОМПАНИЯ)
        print("Добро пожаловать!\n")
        print("Меню:")
        
        for i, пицца in enumerate(self.меню, 1):
            print(f"{i}. {пицца}")
        
        print("\nДля выбора укажите цифру через <ENTER>.")
        print("Для отмены заказа введите -1")
        print("Для подтверждения заказа введите 0")
        
        self.отображать_меню = False

    def обработать_команду(self, пункт_меню):
        try:
            пункт_меню = int(пункт_меню)
            
            if пункт_меню == self.КОМАНДА_ОТМЕНА_ЗАКАЗА:
                if self.заказ is None:
                    print("Заказ не был создан.")
                else:
                    print("Заказ отменен.")
                    self.заказ = None
                    self.отображать_меню = True
                    
            elif пункт_меню == self.КОМАНДА_ПОДТВЕРЖДЕНИЕ_ЗАКАЗА:
                if self.заказ is None or len(self.заказ.заказанные_пиццы) == 0:
                    print("Нет пицц для подтверждения.")
                    return
                
                print("Заказ подтвержен.")
                print(self.заказ)

                try:
                    self.принять_оплату()
                    self.заказ.выполнить()
                    self.заказ = None
                    self.отображать_меню = True
                except Exception:
                    print("Оплата не удалась. Заказ отменен.")
                    self.заказ = None
                    self.отображать_меню = True
                    raise
                    
            elif 1 <= пункт_меню <= len(self.меню):
                if self.заказ is None:
                    self.заказ = Заказ()
                
                выбранная_пицца = self.меню[пункт_меню - 1]
                if пункт_меню == 1:
                    новая_пицца = ПиццаПепперони()
                elif пункт_меню == 2:
                    новая_пицца = ПиццаБарбекю()
                else:
                    новая_пицца = ПиццаДарыМоря()
                
                self.заказ.добавить(новая_пицца)
                
            else:
                raise ValueError("Неверный пункт меню")
                
        except ValueError as e:
            print(f"Не могу распознать команду! Проверьте ввод. ({e})")
        except Exception as e:
            print(f"Во время работы терминала произошла ошибка: {e}")
            self.отображать_меню = True

    def рассчитать_сдачу(self, оплата):
        сумма_заказа = self.заказ.сумма()
        if оплата < сумма_заказа:
            raise ValueError(f"Недостаточно средств. Нужно: {сумма_заказа:.2f} р.")
        return оплата - сумма_заказа

    def принять_оплату(self):
        try:
            сумма_заказа = self.заказ.сумма()
            print(f"Сумма заказа: {сумма_заказа:.2f} р.")
            
            while True:
                try:
                    оплата = float(input("Введите сумму: "))
                    сдача = self.рассчитать_сдачу(оплата)
                    print(f"Вы внесли {оплата:.2f} р. Сдача: {сдача:.2f} р.")
                    return
                except ValueError as e:
                    print(f"Ошибка: {e}")
                    print("Пожалуйста, введите корректную сумму.")
                    
        except Exception as e:
            print("Оплата не удалась. Заказ будет отменен.")
            raise